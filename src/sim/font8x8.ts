export const FONT8X8 = Uint8Array.from(HEX.match(/../g)!.map((h) => parseInt(h, 16)));

/** Glyph rows for a character (unknown characters render as '?'). */
export function glyph(ch: string): Uint8Array {
  let c = ch.charCodeAt(0);
  if (!(c >= 32 && c <= 126)) c = 63;
  return FONT8X8.subarray((c - 32) * 8, (c - 32) * 8 + 8);
}
