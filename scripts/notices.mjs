// Writes THIRD_PARTY_NOTICES.md: the licence notices for everything bundled into the app.
// The package list comes from esbuild's metafiles, so it is exactly what was bundled, plus the
// native packages shipped beside the bundle; each package's own licence text is copied in full. The file is committed (CI checks it is up to
// date) and ships with the app. Electron and Chromium ship their own notices
// (LICENSE.electron.txt, LICENSES.chromium.html) via electron-builder.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

/** node_modules/<pkg>/... or node_modules/@scope/<pkg>/... → package directory. */
function packageDir(input) {
  const m = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input.replaceAll('\\', '/'));
  return m?.[1];
}

function licenceText(dir) {
  const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(n));
  return f ? readFileSync(join(dir, f), 'utf8').trim() : undefined;
}

/** Required by MPL-2.0 for the one MPL file compiled into the app: its notice and where its source is. */
const MPL_NOTICE = `src/video/tables-aspeed-mpl.ts
Copyright (C) 2021 Aspeed Technology Inc.

This Source Code Form is subject to the terms of the Mozilla Public License,
v. 2.0. If a copy of the MPL was not distributed with this file, You can obtain
one at https://mozilla.org/MPL/2.0/.

Source Code Form: https://github.com/AspeedTech-BMC/aspeed_codec (src/jtable.h).`;

/** What the prebuilt binaries of native packages contain beyond the package's own code. */
const NATIVE_CONTENTS = {
  '@napi-rs/keyring': `Its prebuilt binaries are compiled from Rust crates including keyring-core, napi, windows,
security-framework, dbus and secret-service (MIT or Apache-2.0). The Linux binaries also contain
libdbus 1.14 (https://www.freedesktop.org/wiki/Software/dbus/), copyright its contributors, used
under the Academic Free License 2.1.`,
};

/**
 * @param metafiles esbuild metafiles of every bundle that ships in the app
 * @param out output path
 * @param native package directories shipped as node_modules beside the bundle
 * @returns the bundled packages, by name
 */
export function writeNotices(metafiles, out, native = []) {
  const dirs = new Set(native);
  for (const meta of metafiles) for (const input of Object.keys(meta.inputs)) {
    const d = packageDir(input);
    if (d) dirs.add(d);
  }
  // Only what the licences require: each package's copyright and licence text.
  // Packages with identical text (e.g. react, react-dom, scheduler) share one copy.
  const byText = new Map();
  for (const dir of dirs) {
    const name = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).name;
    const own = licenceText(dir);
    if (!own) throw new Error(`${name} has no licence file; add its notice by hand before shipping`);
    const text = NATIVE_CONTENTS[name] ? `${own}\n\n${NATIVE_CONTENTS[name]}` : own;
    byText.set(text, [...(byText.get(text) ?? []), name]);
  }
  const groups = [...byText].map(([text, names]) => ({ names: names.sort(), text })).sort((a, b) => a.names[0].localeCompare(b.names[0]));
  // Licence texts are quoted verbatim in fenced blocks (~~~ cannot clash with their contents).
  const block = (text) => ['~~~text', text, '~~~'];
  const [mplFile, ...mplText] = MPL_NOTICE.split('\n');
  const parts = [
    '# Third-party notices',
    '',
    'IPMI Console includes the third-party software below. This file is generated by',
    '`npm run build` from what is actually bundled into the app; do not edit it by hand.',
    '',
    `## ${mplFile}`,
    '',
    ...block(mplText.join('\n').trim()),
    ...groups.flatMap((g) => ['', `## ${g.names.join(', ')}`, '', ...block(g.text)]),
    '',
  ];
  if (!existsSync(dirname(out))) throw new Error(`missing ${dirname(out)}`);
  writeFileSync(out, parts.join('\n'));
  return groups.flatMap((g) => g.names);
}
