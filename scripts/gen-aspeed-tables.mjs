// Dev-only: generates src/video/tables-aspeed-mpl.ts from ASPEED Technology's
// aspeed_codec (https://github.com/AspeedTech-BMC/aspeed_codec, MPL-2.0),
// src/jtable.h, keeping the MPL notice: the coefficient order, the standard JPEG
// Huffman tables (ITU-T T.81 Annex K.3) and the video engine's 12 quantization tables.
// Usage: node scripts/gen-aspeed-tables.mjs <path/to/aspeed_codec/src/jtable.h>
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(process.argv[2], 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
const grab = (name, len) => {
  const m = new RegExp(`static BYTE ${name}\\[\\d*\\]\\s*=\\s*\\{([^}]*)\\}`).exec(src);
  if (!m) throw new Error(`missing ${name}`);
  const v = m[1].split(',').map((s) => s.trim()).filter(Boolean).map(Number);
  if ((len && v.length !== len) || v.some((x) => !(x >= 0 && x <= 255))) throw new Error(`bad table ${name}`);
  return v;
};
const row = (v) => `[${v.join(', ')}]`;
// Table selector order used by the video engine: 0-7 by rising quality, then 8-11.
const SELECTORS = ['000', '014', '029', '043', '057', '071', '086', '100', '08', '09', '10', '11'];
const out = [
  '/* This Source Code Form is subject to the terms of the Mozilla Public',
  ' * License, v. 2.0. If a copy of the MPL was not distributed with this',
  ' * file, You can obtain one at https://mozilla.org/MPL/2.0/.',
  ' *',
  ' * Data tables from ASPEED Technology\'s aspeed_codec',
  ' * (https://github.com/AspeedTech-BMC/aspeed_codec, src/jtable.h,',
  ' * Copyright (C) 2021 Aspeed Technology Inc., MPL-2.0).',
  ' * Generated by scripts/gen-aspeed-tables.mjs; do not edit by hand.',
  ' */',
  '',
  '/** Zigzag position → coefficient index, padded so corrupt input cannot index past the end. */',
  `export const DEZIGZAG = ${row(grab('dezigzag'))};`,
  '',
  '// Standard Huffman tables (JPEG Annex K.3): code counts per length (index 1..16) and symbols.',
];
for (const [ts, c] of [['DC_LUM', 'std_dc_luminance'], ['DC_CHR', 'std_dc_chrominance'], ['AC_LUM', 'std_ac_luminance'], ['AC_CHR', 'std_ac_chrominance']]) {
  out.push(`export const ${ts}_NRCODES = ${row(grab(`${c}_nrcodes`, 17))};`);
  out.push(`export const ${ts}_VALUES = ${row(grab(`${c}_values`))};`);
}
out.push('', '/** Luma quantization tables, indexed by the frame header\'s table selector 0..11. */');
out.push(`export const QUANT_Y: number[][] = [\n${SELECTORS.map((s) => `  ${row(grab(`Tbl_${s}Y`, 64))},`).join('\n')}\n];`);
out.push('/** Chroma quantization tables, indexed by the frame header\'s table selector 0..11. */');
out.push(`export const QUANT_UV: number[][] = [\n${SELECTORS.map((s) => `  ${row(grab(`Tbl_${s}UV`, 64))},`).join('\n')}\n];`);
writeFileSync(new URL('../src/video/tables-aspeed-mpl.ts', import.meta.url), out.join('\n') + '\n');
console.log('wrote src/video/tables-aspeed-mpl.ts');
