// Dev-only: writes src/textrec/vga-8x16.ts, the IBM VGA 8x16 character shapes
// (code page 437) used by text recognition, from a font_8x16.c-format source:
// 256 glyphs x 16 rows, one byte per row, most significant bit = leftmost pixel.
// Usage: node scripts/gen-vga-font.mjs <path/to/font_8x16.c>
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(process.argv[2], 'utf8');
const body = src.slice(src.indexOf('{', src.indexOf('fontdata_8x16')));
const bytes = [...body.matchAll(/0x([0-9a-fA-F]{2})\s*,/g)].map((m) => parseInt(m[1], 16));
if (bytes.length < 4096) throw new Error(`expected 4096 bytes of glyph data, found ${bytes.length}`);
const hex = Buffer.from(bytes.slice(-4096)).toString('hex');
const rows = hex.match(/.{1,128}/g).map((r) => `  '${r}' +`).join('\n').replace(/ \+$/, ';');
writeFileSync(new URL('../src/textrec/vga-8x16.ts', import.meta.url), `/**
 * IBM VGA 8x16 character shapes (code page 437): the VGA BIOS text font, which
 * is also the Linux console's default font. Bitmap glyph data: 256 glyphs x 16
 * rows, one byte per row, most significant bit = leftmost pixel.
 * Generated by scripts/gen-vga-font.mjs; do not edit by hand.
 */
export const VGA_8X16_HEX =
${rows}
`);
console.log('wrote src/textrec/vga-8x16.ts');
